#!/usr/bin/env python3
"""Generate the GUI.Forms declaration atlas as MyST Markdown for the Sphinx site.

The parser is deliberately conservative: it inventories declarations from the
checked-in public/private headers and definitions from implementation sources.
Human-authored explanations in docs/library/manual.json override the generated
fallbacks. Generated prose never upgrades a candidate or unmeasured claim.

Outputs:

- ``docs/controls/atlas/<slug>.md``  one page per type or enum class;
- ``docs/controls/atlas/index.md``   toctrees grouped by kind and header area;
- ``docs/controls/atlas/captures/``  the capture PNGs referenced by pages,
  copied from ``docs/library/captures/`` (the source of truth) so the Sphinx
  tree is self-contained;
- ``docs/library/manifest.json``     the machine-readable page inventory.

``--check`` regenerates into a temporary directory and fails when the committed
atlas or manifest differs, so CI can detect a stale atlas:

    python3 tools/generate_library_docs.py --check
"""

