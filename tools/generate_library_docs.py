def category_slug(category: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", category.lower()).strip("-") + "-controls"


def heading_anchor(text: str) -> str:
    """The anchor MyST derives for a heading (myst_heading_anchors)."""
    slug = re.sub(r"[^\w\- ]", "", text.strip().lower())
    return slug.replace(" ", "-")


@dataclass
class Method:
    name: str
    signature: str
    access: str = "public"
    comment: str = ""


@dataclass
class Declaration:
    """A data member, constant or type alias, with its leading comment."""
    text: str
    comment: str = ""


@dataclass
class TypeRecord:
    name: str
    kind: str
    header: str
    line: int
    declaration: str = ""
    namespace: str = ""
    owner: str = ""
    bases: list[str] = field(default_factory=list)
    methods: list[Method] = field(default_factory=list)
    fields: list[Declaration] = field(default_factory=list)
    comment: str = ""

    @property
    def display_name(self) -> str:
        return f"{self.owner}::{self.name}" if self.owner else self.name

    @property
    def qualified_name(self) -> str:
        parts = [part for part in (self.namespace, self.owner, self.name) if part]
        return "::".join(parts)


@dataclass
class EnumRecord:
    name: str
    header: str
    line: int
    namespace: str = ""
    owner: str = ""
    values: list[str] = field(default_factory=list)

    @property
    def display_name(self) -> str:
        return f"{self.owner}::{self.name}" if self.owner else self.name


@dataclass
class HeaderScope:
    """Namespace-scope functions, constants and aliases declared in one header."""
    header: str
    namespace: str
    functions: list[Method] = field(default_factory=list)
    declarations: list[Declaration] = field(default_factory=list)


