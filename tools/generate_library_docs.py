#!/usr/bin/env python3
"""Generate the GUI.Forms API reference in the layout of the NumPy reference.

Declarations come from the checked-in public headers under include/gui_forms/
(tools/api_docs_parse.py); anything in a ``detail`` namespace or directory is
left out. Descriptions come only from reviewed sources, in priority order:

1. the numpydoc-style docstrings in docs/library/docstrings/<TypeName>.rst;
2. the hand-written narratives in docs/library/manual.json;
3. the reviewed contracts in docs/reference/contracts/*.json;
4. the ``//`` comment directly above a declaration in its header.

Nothing is inferred from a signature. A docstring may only describe parameters,
properties, events and methods the header declares; anything else is an error.

Output, all reStructuredText for Sphinx's C++ domain:

- docs/api/index.rst                       the reference home page;
- docs/api/controls.rst, controls.<c>.rst  stock controls by function category;
- docs/api/library.rst, library.<t>.rst    the rest of the library by topic;
- docs/api/generated/<namespace>.<Type>.rst  one page per stock control and per
  documented type, laid out like a numpydoc class page.

It also writes tests/doc_examples_tests.cpp, which compiles and runs every
example in the docstrings, so no example can drift from the API.

``--check`` regenerates into a temporary directory and fails when the committed
output differs:

    python3 tools/generate_library_docs.py --check
"""
