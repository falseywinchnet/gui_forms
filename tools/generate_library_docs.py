"""Generate the GUI.Forms API reference as MyST Markdown for the Sphinx site.

Declarations are read from the checked-in public headers under
``include/gui_forms/``; anything inside a ``detail`` namespace or directory is
left out. Descriptions come only from reviewed sources: the hand-written
narratives in ``docs/library/manual.json`` and the reviewed remarks in
``docs/reference/contracts/*.json``. Nothing is inferred from a signature, so a
member without a reviewed description is listed by its signature alone.

Stock controls are grouped by the function category recorded in
``manifests/controls.json``; every other public type is grouped by header area.
The output is one page per group plus an index, a few dozen pages in all:

- ``docs/api/index.md``
- ``docs/api/<group>.md``

Private headers under ``src/`` are still parsed so that every narrative in
manual.json must resolve to exactly one declaration, but they are never
published.

``--check`` regenerates into a temporary directory and fails when the committed
pages differ, so CI can detect a stale reference:

    python3 tools/generate_library_docs.py --check
"""

