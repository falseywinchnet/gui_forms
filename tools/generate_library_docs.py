def differences(expected: Path, actual: Path) -> list[str]:
    """Return relative paths that differ between two directory trees."""
    found: list[str] = []
    comparison = filecmp.dircmp(expected, actual)

    def walk(node: filecmp.dircmp, prefix: str) -> None:
        for name in node.left_only:
            found.append(f"only in committed tree: {prefix}{name}")
        for name in node.right_only:
            found.append(f"missing from committed tree: {prefix}{name}")
        for name in node.diff_files + node.funny_files:
            found.append(f"content differs: {prefix}{name}")
        for name, child in node.subdirs.items():
            walk(child, f"{prefix}{name}/")

    walk(comparison, "")
    return sorted(found)


def check() -> int:
    with tempfile.TemporaryDirectory(prefix="gui-forms-api-") as scratch:
        fresh = Path(scratch) / "api"
        fresh_examples = Path(scratch) / EXAMPLES.name
        render(fresh, fresh_examples)
        problems: list[str] = []
        if not API.is_dir():
            problems.append(f"missing committed reference directory: {API}")
        else:
            problems += differences(API, fresh)
        for committed in (EXAMPLES, COMPILE_ONLY):
            fresh_file = fresh_examples.with_name(committed.name)
            if not committed.is_file() or not filecmp.cmp(committed, fresh_file, shallow=False):
                problems.append(f"content differs: {committed.relative_to(GUI_FORMS)}")
    if problems:
        print("GUI.Forms API reference is stale; run python3 tools/generate_library_docs.py",
              file=sys.stderr)
        for problem in problems[:50]:
            print("  " + problem, file=sys.stderr)
        if len(problems) > 50:
            print(f"  ... {len(problems) - 50} more", file=sys.stderr)
        return 1
    print("GUI.Forms API reference check: PASS (committed pages match the headers and docstrings)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="regenerate into a temporary directory and fail if the committed "
                             "pages or the examples test differ")
    parser.add_argument("--output", type=Path, default=API, help="output directory (default: docs/api)")
    parser.add_argument("--examples", type=Path, default=EXAMPLES,
                        help="examples test source (default: tests/doc_examples_tests.cpp)")
    args = parser.parse_args()
    if args.check:
        return check()
    result = render(args.output.resolve(), args.examples.resolve())
    print(f"GUI.Forms API reference: {result['pages']} pages; {result['types']} types and "
          f"{result['enums']} enumerations; {result['own_pages']} with their own page, "
          f"{result['docstrings']} with a docstring")
    return 0


