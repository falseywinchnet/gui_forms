# --- validation and output --------------------------------------------------

def validate(types: list[TypeRecord], manual: dict, pages: dict[str, str],
             copied: set[str]) -> None:
    """Fail on inconsistencies between manual.json and the declarations.

    A review that no longer resolves to exactly one declaration, a method
    explanation for a method that no longer exists, an invalid method scope,
    or a referenced capture that is missing are errors in every mode.
    """
    if len(pages) != len(set(pages)):
        raise RuntimeError("generated documentation contains duplicate page paths")
    for name in copied:
        if not (CAPTURE_SOURCE / name).is_file():
            raise RuntimeError(f"missing capture: {CAPTURE_SOURCE / name}")
    for review_key, review in manual.get("types", {}).items():
        name = review.get("name", review_key)
        capture = review.get("capture")
        if capture and not (LIBRARY / capture).is_file():
            raise RuntimeError(f"{name} references missing capture: {capture}")
        candidates = [record for record in types if record.name == name]
        declaration_header = review.get("declaration_header")
        if declaration_header:
            candidates = [record for record in candidates
                          if record.header == declaration_header]
        if len(candidates) != 1:
            raise RuntimeError(
                f"manual review {name} resolves to {len(candidates)} declarations")
        method_scope = review.get("method_scope", "public")
        if method_scope not in {"public", "all"}:
            raise RuntimeError(
                f"{name} review has invalid method_scope: {method_scope}")
        if "methods" not in review:
            continue
        discovered = {
            method.name for method in candidates[0].methods
            if method_scope == "all" or method.access == "public"
        }
        stale = sorted(set(review["methods"]) - discovered)
        if stale:
            raise RuntimeError(
                f"{name} review has stale method explanations: {stale}")


def strict_failures(report: Report) -> list[str]:
    failures: list[str] = []
    if report.unreviewed_types:
        failures.append("manual type narratives are missing: " +
                        ", ".join(report.unreviewed_types))
    if report.captures_pending:
        failures.append("visual declarations lack verified capture evidence: " +
                        ", ".join(report.captures_pending))
    if report.grouped_migrations:
        failures.append("grouped source migrations remain: " +
                        ", ".join(report.grouped_migrations))
    if report.declaration_derived_methods:
        failures.append("reviewed types have unexplained methods: " +
                        ", ".join(report.declaration_derived_methods))
    return failures


def generate(atlas: Path, manifest_path: Path, strict: bool) -> Report:
    manual = json.loads(MANUAL_PATH.read_text(encoding="utf-8"))
    types, enums = declarations()
    definition_map(types)
    mark_visual(types)
    used: set[str] = set()
    for record in sorted(types, key=lambda item: (not item.visual, item.name, item.header)):
        record.slug = unique_slug(snake_case(record.name), used)
    for enum in sorted(enums, key=lambda item: (item.name, item.header)):
        enum.slug = unique_slug("enum_" + snake_case(enum.name), used)

    report = Report(types=len(types), enums=len(enums))
    copied: set[str] = set()
    pages: dict[str, str] = {}
    type_manifest: list[dict] = []
    for record in types:
        page, entry = type_page(record, manual, report, copied)
        pages[f"{record.slug}.md"] = page
        type_manifest.append(entry)
    enum_manifest: list[dict] = []
    for enum in enums:
        page, entry = enum_page(enum)
        pages[f"{enum.slug}.md"] = page
        enum_manifest.append(entry)
    validate(types, manual, pages, copied)
    pages["index.md"] = index_page(types, enums, report)

    if atlas.exists():
        shutil.rmtree(atlas)
    (atlas / "captures").mkdir(parents=True)
    for name, page in pages.items():
        (atlas / name).write_text(page, encoding="utf-8")
    for name in sorted(copied):
        shutil.copyfile(CAPTURE_SOURCE / name, atlas / "captures" / name)

    type_manifest.sort(key=lambda item: (not item["visual"], item["name"], item["header"]))
    enum_manifest.sort(key=lambda item: (item["name"], item["header"]))
    payload = {
        "schema": 2,
        "atlas": atlas.relative_to(GUI_FORMS).as_posix() if atlas.is_relative_to(GUI_FORMS)
        else ATLAS.relative_to(GUI_FORMS).as_posix(),
        "types": type_manifest,
        "enums": enum_manifest,
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    if strict:
        failures = strict_failures(report)
        if failures:
            raise RuntimeError("\n".join(failures))
    return report


def differences(expected: Path, actual: Path) -> list[str]:
    """Return relative paths that differ between two directory trees."""
    found: list[str] = []
    comparison = filecmp.dircmp(expected, actual)

    def walk(node: filecmp.dircmp, prefix: str) -> None:
        for name in node.left_only:
            found.append(f"only in committed tree: {prefix}{name}")
        for name in node.right_only:
            found.append(f"missing from committed tree: {prefix}{name}")
        for name in node.diff_files + node.funny_files:
            found.append(f"content differs: {prefix}{name}")
        for name, child in node.subdirs.items():
            walk(child, f"{prefix}{name}/")

    walk(comparison, "")
    return sorted(found)


def check() -> int:
    with tempfile.TemporaryDirectory(prefix="gui-forms-atlas-") as scratch:
        scratch_root = Path(scratch)
        atlas = scratch_root / "atlas"
        manifest = scratch_root / MANIFEST_NAME
        generate(atlas, manifest, strict=False)
        problems: list[str] = []
        if not ATLAS.is_dir():
            problems.append(f"missing committed atlas directory: {ATLAS}")
        else:
            problems += differences(ATLAS, atlas)
        committed_manifest = LIBRARY / MANIFEST_NAME
        if not committed_manifest.is_file() or not filecmp.cmp(
                committed_manifest, manifest, shallow=False):
            problems.append(f"content differs: {committed_manifest.relative_to(GUI_FORMS)}")
    if problems:
        print("GUI.Forms atlas is stale; run python3 tools/generate_library_docs.py",
              file=sys.stderr)
        for problem in problems[:50]:
            print("  " + problem, file=sys.stderr)
        if len(problems) > 50:
            print(f"  ... {len(problems) - 50} more", file=sys.stderr)
        return 1
    print("GUI.Forms atlas check: PASS (committed atlas matches the headers)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="regenerate into a temporary directory and fail if "
                             "the committed atlas or manifest differs")
    parser.add_argument("--strict", action="store_true",
                        help="fail when any type lacks a hand-reviewed narrative, any "
                             "visual type lacks a capture, any reviewed type has "
                             "unexplained methods, or grouped migrations remain")
    parser.add_argument("--output", type=Path, default=ATLAS,
                        help="atlas output directory (default: docs/controls/atlas)")
    parser.add_argument("--manifest", type=Path, default=LIBRARY / MANIFEST_NAME,
                        help="manifest path (default: docs/library/manifest.json)")
    args = parser.parse_args()
    if args.check:
        return check()
    report = generate(args.output.resolve(), args.manifest.resolve(), args.strict)
    print(f"GUI.Forms library docs: PASS ({report.types} types, {report.enums} enums; "
          f"{len(report.unreviewed_types)} types without hand-reviewed narratives; "
          f"{len(report.captures_pending)} visual types with captures pending; "
          f"{len(report.grouped_migrations)} grouped migrations pending)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
